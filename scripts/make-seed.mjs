#!/usr/bin/env node
// Writes supabase/seed/mobile-sample.sql from the bundled sample (src/sample), for a LOCAL replica
// of the backend only. Every insert is `on conflict do nothing`, so it never overwrites anything.
//   node scripts/make-seed.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const dir = new URL('../src/sample/', import.meta.url);
const read = (f) => JSON.parse(readFileSync(new URL(f, dir), 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [
  '-- Seed for a LOCAL replica of the nter.pro backend (supabase start in ddllabs/niyantran).',
  '-- Generated by scripts/make-seed.mjs from src/sample. Never run this against NTER (production):',
  '-- NTER already holds the real data. Inserts skip rows that already exist.',
  'begin;',
  '',
  '-- AI models (the list nter.pro had enabled on 26 Oct 2026)',
];
for (const m of read('ai-models.json')) {
  lines.push(`insert into public.ai_models (model_id, label, vendor, tier, efforts, enabled, is_default, sort_order, min_plan) values (${q(m.model_id)}, ${q(m.label)}, ${q(m.vendor || '')}, ${Number(m.tier) || 2}, array[${(m.efforts || []).map(q).join(', ')}]::text[], true, ${m.is_default ? 'true' : 'false'}, ${Number(m.sort_order) || 100}, ${q(m.min_plan || 'plus')}::public.app_plan) on conflict (model_id) do nothing;`);
}
lines.push('', '-- Desk records for search (up to 10 per module)');
const scalar = (row) => Object.fromEntries(Object.entries(row).filter(([, v]) => v != null && v !== '' && typeof v !== 'object'));
const modules = {};
for (const f of readdirSync(dir).filter((n) => /^modules-.*\.json$/.test(n))) Object.assign(modules, read(f));
Object.assign(modules, read('feed-store.json'));
// desk_rows.tier holds the desk id; feature-feed tiers differ for four desks.
const DESK = { geopolitics: 'global', judiciary: 'law', finance: 'economics', climate: 'carbon', local: 'state' };
let n = 0;
for (const m of Object.values(modules)) {
  const tier = DESK[m.tier] || m.tier;
  for (const row of (m.rows || []).filter((r) => r.status !== 'source_status').slice(0, 10)) {
    const r = scalar(row);
    const key = createHash('sha1').update(`${m.feature}|${JSON.stringify(r)}`).digest('hex').slice(0, 24);
    const text = Object.entries(r).map(([k, v]) => `${k}: ${v}`).join('\n');
    lines.push(`insert into public.desk_rows (tier, feature, row_key, "row", record_text, snapshot_at) values (${q(tier)}, ${q(m.feature)}, ${q(key)}, ${q(JSON.stringify(r))}::jsonb, ${q(text)}, now()) on conflict do nothing;`);
    n += 1;
  }
}
lines.push('', 'commit;', '');
writeFileSync(new URL('../supabase/seed/mobile-sample.sql', import.meta.url), lines.join('\n'));
console.log(`supabase/seed/mobile-sample.sql: ${read('ai-models.json').length} models, ${n} desk records`);
